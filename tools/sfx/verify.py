"""Listens to the shipped set and writes tools/sfx/REPORT.md (+ verify.json).

    <earshot python> -I tools/sfx/verify.py [--report-only]

Per file, from the shipped OGG: our meters (manifest), ffmpeg ebur128 (momentary max, true peak) as an independent
cross-check, the strongest partials, and earshot's describe + match of the sound's description against "harsh /
buzzy / sad / cheap" alternatives (one process, models loaded once). Exit 1 when a hard gate fails.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import sfxlib as s  # noqa: E402

ROOT = HERE.parent.parent
BAD = ["an error buzz", "a harsh alarm beep", "a sad descending tone", "a cheap synthesizer beep"]
GATES = {"lead_silence_ms": 10.0, "true_peak_dbtp": -1.0, "total_bytes": 900_000, "below_300hz_pct": 15.0}
MAX_LEN = {"session_end": 3.0, "mic_open": 0.15}


def ffmpeg_meters(path: Path) -> dict:
    err = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-v", "verbose", "-i", str(path), "-af",
                          "apad=pad_dur=0.5,ebur128=peak=true:framelog=verbose", "-f", "null", "-"],
                         capture_output=True, text=True).stderr
    m = [float(v) for v in re.findall(r"M:\s*(-?\d+\.\d+)", err)]
    tp = re.findall(r"True peak:\s*\n\s*Peak:\s*(-?[\d.]+)", err)
    return {"ff_momentary_max": max(m) if m else None, "ff_true_peak": float(tp[0]) if tp else None}


def main() -> int:
    man = json.loads((HERE / "manifest.json").read_text(encoding="utf-8"))
    if "--report-only" in sys.argv:
        v = json.loads((HERE / "verify.json").read_text(encoding="utf-8"))
        write_report(man, v["rows"], v["fails"])
        return 1 if v["fails"] else 0
    from earshot import api
    rows, fails = [], []
    for e in man["sounds"]:
        path = ROOT / "legacy/design/src/main/assets" / e["file"]
        x = s.load(path)
        m = e["measured_from_ogg"]
        d = api.describe(str(path), top=3)
        mt = api.match(str(path), e["earshot_query"], alts=BAD)
        r = {"name": e["name"], **m, **ffmpeg_meters(path),
             "partials": [f"{n}{c:+.0f}" for _, n, c in s.pitches(x, 3, fmin=250)],
             "earshot_tags": [(t["term"], round(t["z"], 1)) for t in d["top_tags"][:3]],
             "earshot_query": e["earshot_query"], "earshot_z": round(mt["z"], 1),
             "p_vs_bad": round(mt.get("p_vs_alts", 0), 2), "brightness_hz": d["measurements"].get("brightness_hz")}
        rows.append(r)
        if m["lead_silence_ms"] > GATES["lead_silence_ms"]:
            fails.append(f"{e['name']}: lead {m['lead_silence_ms']} ms")
        if m["true_peak_dbtp"] > GATES["true_peak_dbtp"]:
            fails.append(f"{e['name']}: true peak {m['true_peak_dbtp']}")
        if m["energy_below_300hz_pct"] > GATES["below_300hz_pct"]:
            fails.append(f"{e['name']}: {m['energy_below_300hz_pct']}% under 300 Hz")
        if m["duration_s"] > MAX_LEN.get(e["name"], 2.0):
            fails.append(f"{e['name']}: {m['duration_s']} s")
        print(e["name"], r["earshot_z"], r["p_vs_bad"], r["earshot_tags"][:2], flush=True)
    if man["total_bytes"] > GATES["total_bytes"]:
        fails.append(f"total {man['total_bytes']} B")
    (HERE / "verify.json").write_text(json.dumps({"rows": rows, "fails": fails}, indent=2, ensure_ascii=False) + "\n",
                                      encoding="utf-8")
    write_report(man, rows, fails)
    print("FAILS:", fails or "none")
    return 1 if fails else 0


def write_report(man: dict, rows: list[dict], fails: list[str]) -> None:
    by = {e["name"]: e for e in man["sounds"]}
    T = man["levels"]["tiers_max_momentary_lufs"]
    L = ["# Fonia sound effects v2: measured report\n",
         "Generated by `tools/sfx/verify.py` from the shipped OGG files (`legacy/design/src/main/assets/sfx/`). "
         "Rebuild with `tools/sfx/build.py` (candidates are scored by `tools/sfx/audition.py` into `audition.json`), "
         "then re-run this. Nobody has listened: every statement is a measurement or an earshot reading.\n",
         "v2 replaces the v1 set the owner rejected (thin synthesised beeps). Direction: a top children's learning game, "
         "juicy, bubbly, sparkling; sources in order ElevenLabs sound effects, earshot's bank, computed layers only "
         "underneath.\n",
         f"- **Family**: {man['family']}.",
         f"- **Format**: {man['format']}; total **{man['total_bytes'] / 1024:.0f} KB** for {len(rows)} files (gate 900 KB).",
         f"- **Levels**: max momentary loudness per tier (LUFS-M, BS.1770, 400 ms windows; ours steps 10 ms, ffmpeg 100 ms): "
         f"strong {T['strong']}, medium {T['medium']}, soft {T['soft']}, subtle {T['subtle']}; his voice clips sit near "
         f"-15 LUFS, so every effect is 2-11 dB under the voice. True-peak ceiling -3 dBTP before the codec (gate <= -1 after).",
         f"- **Chain**: {man['chain']}.",
         "- **Key**: each tonal sound is resampled by the shift (<= 150 cents) that best lands its strongest partials on "
         "C major's white keys (`key` column: shift / remaining weighted error in cents; Foni's glides and the whooshes "
         "are not tonal). The two tap variants and the retake are transposed and re-landed on white keys.",
         f"- **ElevenLabs**: {man['elevenlabs_generations']['v1']} generations in v1, {man['elevenlabs_generations']['v2']} in v2; "
         "every raw file is kept in `tools/sfx/raw/elevenlabs/` (v2 in `v2/`), every v2 candidate's earshot reading in `audition.json`.\n",
         "| # | sound | source | tier | ch | dur s | M max (ours / ffmpeg) | TP dBTP | lead ms | <300 Hz | key c | earshot: query z, p vs harsh/sad | earshot hears | KB |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        e = by[r["name"]]
        key = f"{e.get('key_shift_cents', '-')}/{e.get('key_error_cents', '-')}"
        L.append(f"| {i} | `{r['name']}` | {e['source']} | {e['tier']} | {r['channels']} | {r['duration_s']:.3f} | "
                 f"{r['momentary_max_lufs']} / {r['ff_momentary_max']} | {r['true_peak_dbtp']} | {r['lead_silence_ms']} | "
                 f"{r['energy_below_300hz_pct']}% | {key} | {r['earshot_z']}, {r['p_vs_bad']} | "
                 f"{'; '.join(f'{t} ({z})' for t, z in r['earshot_tags'])} | {e['measured_from_ogg']['ogg_bytes'] / 1024:.1f} |")
    L += ["",
          "*p vs harsh/sad* = earshot's forced choice between the sound's own description and 'an error buzz', 'a harsh "
          "alarm beep', 'a sad descending tone', 'a cheap synthesizer beep' (1.00 = clearly its own description). earshot "
          "z >= 3 strong, 2.5-3 plausible, 2-2.5 weak. Short UI sounds (< 0.3 s) are padded to 10 s by the models, so a low "
          "z on a 90 ms tap is weak evidence; its tags matter more. Bird calls read as 'a balloon squeak' to CLAP; their "
          "realness (p_real 0.91-0.99, real recording) is in `audition.json`.\n",
          "## Why each sound (the reading it was chosen on)\n"]
    for e in man["sounds"]:
        L.append(f"- `{e['name']}` ({e['source']}): {e['why']}. Source: {e['provenance']}.")
    L += ["", "## Gates\n",
          f"Lead silence <= {GATES['lead_silence_ms']} ms, true peak <= {GATES['true_peak_dbtp']} dBTP after encoding, "
          f"energy under 300 Hz <= {GATES['below_300hz_pct']} % (the good's soft thump is deliberate), mic_open <= 0.15 s, "
          "session end <= 3 s, set <= 900 KB.\n",
          "Result: " + ("**all pass**." if not fails else "FAIL: " + "; ".join(fails)) + "\n",
          "## Licences\n",
          "ElevenLabs sound effects: generated for this project under the account's ElevenLabs terms. earshot bank: MIT "
          "(earshot 0.4.1; its `fit/` sounds are code fitted to CC0 recordings). Computed layers (thump, room, saturation): "
          "`tools/sfx/sfxlib.py`, Fonia's own. No file of the iOS content is used any more.\n",
          "## Playback and the quiet rule (unchanged from v1)\n",
          "`SfxGate` (legacy/design) is the one place that decides: nothing starts while a take captures; "
          "`AudioHub.startListening` waits until the last effect has ended + 150 ms (60 ms latency allowed); in the 150 ms "
          "after the capture closes an outcome is deferred, a UI sound dropped; two effects closer than 120 ms never stack; "
          "the in-app switch, silent / vibrate ringer and Do Not Disturb silence everything; TalkBack mutes the chrome "
          "sounds. `SfxPlayer`: one preloaded `SoundPool` (4 streams, media volume). Taps rotate over three variants, "
          "Foni over six calls. His `SoundEffects` player is no longer created (`AppModel`: no effects folder), and "
          "`AudioHub.effectsMuted` is FoniaSfx's switch. Proof: `SfxQuietRuleTests` (1,000 random sessions through the "
          "real AudioHub, plus merge / deferral / switch / round-robin / asset tests).\n",
          "## Not verified\n",
          "Nobody has listened; taste is the owner's call from `output/sunete/v2/00_showreel.mp3`. Not run on a phone "
          "speaker; output latency and haptic timing unmeasured; the emulator was not used (others were on it).\n"]
    (HERE / "REPORT.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    sys.exit(main())
